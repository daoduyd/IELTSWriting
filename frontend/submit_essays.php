// Hàm tính điểm IELTS Writing
function gradeIELTSWriting($content, $word_count, $category) {
    $scores = ['task_achievement' => 0, 'coherence' => 0, 'lexical' => 0, 'grammar' => 0];
    $feedback = [];

    // Task Achievement
    $min_words = ($category === 'Writing Task 1') ? 150 : 250;
    if ($word_count >= $min_words) {
        $scores['task_achievement'] = 7;
        $feedback['task_achievement'] = "Đạt yêu cầu về số từ và cấu trúc cơ bản.";
    } elseif ($word_count >= $min_words * 0.8) {
        $scores['task_achievement'] = 6;
        $feedback['task_achievement'] = "Gần đạt số từ tối thiểu, cần phát triển ý thêm.";
    } else {
        $scores['task_achievement'] = 5;
        $feedback['task_achievement'] = "Không đủ số từ, nội dung chưa hoàn thiện.";
    }

    // Coherence and Cohesion
    $sentences = preg_split('/[.!?]+/', $content, -1, PREG_SPLIT_NO_EMPTY);
    $sentence_count = count($sentences);
    $avg_sentence_length = $sentence_count > 0 ? $word_count / $sentence_count : 0;
    if ($avg_sentence_length > 5 && $avg_sentence_length < 20) {
        $scores['coherence'] = 7;
        $feedback['coherence'] = "Các ý liên kết tốt, độ dài câu hợp lý.";
    } else {
        $scores['coherence'] = 6;
        $feedback['coherence'] = "Cần cải thiện sự liên kết hoặc độ dài câu.";
    }

    // Lexical Resource
    $words = str_word_count($content, 1);
    $unique_words = count(array_unique($words));
    $lexical_ratio = $word_count > 0 ? $unique_words / $word_count : 0;
    if ($lexical_ratio > 0.5) {
        $scores['lexical'] = 7;
        $feedback['lexical'] = "Từ vựng phong phú và phù hợp.";
    } else {
        $scores['lexical'] = 6;
        $feedback['lexical'] = "Từ vựng còn hạn chế hoặc lặp lại.";
    }

    // Grammatical Range and Accuracy (giả định đơn giản)
    $scores['grammar'] = 6; // Cần công cụ phân tích ngữ pháp để đánh giá chính xác
    $feedback['grammar'] = "Cấu trúc ngữ pháp cơ bản ổn, cần thêm câu phức tạp.";

    // Tổng điểm
    $total_score = array_sum($scores) / 4;
    return [
        'scores' => $scores,
        'total' => round($total_score, 1),
        'feedback' => $feedback
    ];
}

// Hàm kiểm tra phụ thuộc AI
function checkAIDependency($content) {
    $ai_signatures = [
        "perfectly structured", "in conclusion, it can be said", "this essay will discuss",
        "generated by", "AI-assisted"
    ];
    $ai_score = 0;
    foreach ($ai_signatures as $signature) {
        if (stripos($content, $signature) !== false) {
            $ai_score += 20;
        }
    }
    $words = str_word_count($content, 1);
    $unique_words = count(array_unique($words));
    $word_count = count($words);
    if ($word_count > 0 && $unique_words / $word_count > 0.9) {
        $ai_score += 30;
    }
    return min($ai_score, 100);
}

// Hàm đánh giá nguy cơ đạo văn (giả định đơn giản)
function checkPlagiarismRisk($content) {
    $common_phrases = ["to sum up", "it is clear that", "in my opinion"];
    $risk_score = 0;
    foreach ($common_phrases as $phrase) {
        if (stripos($content, $phrase) !== false) {
            $risk_score += 10;
        }
    }
    if ($risk_score > 20) return 'High';
    elseif ($risk_score > 10) return 'Medium';
    else return 'Low';
}

